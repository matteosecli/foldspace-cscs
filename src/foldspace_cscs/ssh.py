"""A private OpenSSH setup for the plug-in.

Every ssh call made by this plug-in (and by upstream Foldspace, through a tiny
`ssh` wrapper put first on its PATH) uses `ssh -F <state>/ssh_config`, which
only contains hosts named `foldspace-cscs-*`. The user's ~/.ssh/config is never
read; it is only touched while a `vscode` session runs, to let VS Code desktop
see those hosts (one `Include` line, removed on exit; see `vscode_include`).
"""

from __future__ import annotations

import os
import shutil
import stat
import subprocess
from contextlib import contextmanager
from pathlib import Path

from .clusters import CLUSTERS, JUMP_HOST

STATE_DIR = Path(os.environ.get("FOLDSPACE_CSCS_HOME", Path.home() / ".config" / "foldspace-cscs"))
SSH_CONFIG = STATE_DIR / "ssh_config"
KNOWN_HOSTS = STATE_DIR / "known_hosts"
SHIM_DIR = STATE_DIR / "bin"
SESSIONS_DIR = STATE_DIR / "vscode-sessions"
USER_SSH_CONFIG = Path.home() / ".ssh" / "config"
INCLUDE_BEGIN = "# >>> foldspace-cscs: added while a vscode session runs, removed on exit >>>"
INCLUDE_END = "# <<< foldspace-cscs <<<"


def real_ssh() -> str:
    """Absolute path of the system ssh (never our own wrapper)."""
    path = os.environ.get("PATH", "")
    clean = os.pathsep.join(p for p in path.split(os.pathsep) if Path(p) != SHIM_DIR)
    found = shutil.which("ssh", path=clean)
    if not found:
        raise RuntimeError("OpenSSH client `ssh` not found in PATH")
    return found


def write_config(user: str, key: Path) -> None:
    """(Re)write the private ssh config and the `ssh` wrapper."""
    STATE_DIR.mkdir(parents=True, exist_ok=True, mode=0o700)
    SHIM_DIR.mkdir(parents=True, exist_ok=True, mode=0o700)
    cert = Path(f"{key}-cert.pub")

    lines = [
        "# Generated by foldspace-cscs on every run: do not edit.",
        "# Only used through `ssh -F` by foldspace-cscs; your ~/.ssh/config is not read.",
        "",
        "Host foldspace-cscs-ela",
        f"  HostName {JUMP_HOST}",
        "",
    ]
    for c in CLUSTERS.values():
        lines += [
            f"Host {c.alias}",
            f"  HostName {c.host}",
            "  ProxyJump foldspace-cscs-ela",
            "",
        ]
    # VS Code desktop (Remote-SSH) into the node of the running vscode job:
    # the login node finds the node and relays to its sshd, then the job's
    # uenv is entered with `uenv start` (see toolbox/bin/vscode-desktop-*.sh).
    # The node changes from job to job, so its host key is not pinned; the
    # connection is relayed by the (verified) login node.
    for c in CLUSTERS.values():
        bin_dir = f"~/.foldspace-cscs/{c.name}/toolbox/bin"
        lines += [
            f"Host {c.vscode_alias}",
            f'  ProxyCommand "{real_ssh()}" -F "{SSH_CONFIG}" {c.alias} "bash {bin_dir}/vscode-desktop-proxy.sh"',
            "  RequestTTY yes",
            f"  RemoteCommand bash {bin_dir}/vscode-desktop-shell.sh",
            "  BatchMode no",
            "  StrictHostKeyChecking no",
            "  UserKnownHostsFile /dev/null",
            "  ServerAliveInterval 60",
            "",
        ]
    lines += [
        "Host foldspace-cscs-*",
        f"  User {user}",
        f"  IdentityFile {key}",
        f"  CertificateFile {cert}",
        "  IdentitiesOnly yes",
        # Foldspace parses command output and runs ssh non-interactively:
        # never prompt, never allocate a TTY, no RemoteCommand.
        "  BatchMode yes",
        "  RequestTTY no",
        "  ConnectTimeout 20",
        "  ServerAliveInterval 30",
        "  ServerAliveCountMax 6",
        # Trust-on-first-use, stored in our own file first.
        "  StrictHostKeyChecking accept-new",
        f"  UserKnownHostsFile {KNOWN_HOSTS} ~/.ssh/known_hosts",
        # Silence banners/warnings that would pollute captured stderr.
        "  LogLevel ERROR",
        "",
    ]
    _write_private(SSH_CONFIG, "\n".join(lines))

    shim = SHIM_DIR / "ssh"
    _write_private(
        shim,
        "#!/usr/bin/env bash\n"
        "# Wrapper used by foldspace-cscs so that upstream Foldspace only sees our private ssh config.\n"
        "# Also: Foldspace lists your jobs with `squeue --me` to offer reconnecting to them, but\n"
        "# squeue omits jobs in hidden partitions (e.g. jupyterhub at CSCS) unless given -a.\n"
        'args=("$@")\n'
        'n=${#args[@]}\n'
        '(( n > 0 )) && args[n-1]=${args[n-1]//"squeue --me"/"squeue -a --me"}\n'
        f'exec "{real_ssh()}" -F "{SSH_CONFIG}" "${{args[@]}}"\n',
    )
    shim.chmod(stat.S_IRWXU)


def _write_private(path: Path, content: str) -> None:
    old = os.umask(0o077)
    try:
        path.write_text(content)
    finally:
        os.umask(old)


def run(alias: str, command: str, *, input: bytes | None = None, capture: bool = True,
        timeout: float | None = 120) -> subprocess.CompletedProcess:
    """Run `command` on `alias` with the private config."""
    return subprocess.run(
        [real_ssh(), "-F", str(SSH_CONFIG), alias, command],
        input=input,
        capture_output=capture,
        timeout=timeout,
    )


def env_with_shim() -> dict:
    """Environment in which a plain `ssh` resolves to our wrapper."""
    env = dict(os.environ)
    env["PATH"] = f"{SHIM_DIR}{os.pathsep}{env.get('PATH', '')}"
    return env


# --- VS Code desktop: temporary Include in ~/.ssh/config ---------------------

def _strip_include(text: str) -> str:
    out, skipping = [], False
    for line in text.splitlines(keepends=True):
        if line.rstrip("\n") == INCLUDE_BEGIN:
            skipping = True
        elif skipping and line.rstrip("\n") == INCLUDE_END:
            skipping = False
        elif not skipping:
            out.append(line)
    return "".join(out).lstrip("\n") if text.startswith(INCLUDE_BEGIN) else "".join(out)


def _rewrite_user_config(add: bool) -> None:
    """Add or remove our Include block at the top of ~/.ssh/config.

    It must come first: OpenSSH applies an Include placed after a Host line
    only to that host. A symlinked config (dotfiles) is edited in place.
    """
    path = USER_SSH_CONFIG.resolve() if USER_SSH_CONFIG.is_symlink() else USER_SSH_CONFIG
    old = path.read_text() if path.exists() else ""
    new = _strip_include(old)
    if add:
        new = f"{INCLUDE_BEGIN}\nInclude {SSH_CONFIG}\n{INCLUDE_END}\n\n" + new
    if new == old:
        return
    path.parent.mkdir(parents=True, exist_ok=True, mode=0o700)
    mode = stat.S_IMODE(path.stat().st_mode) if path.exists() else 0o600
    tmp = path.with_name(path.name + ".foldspace-cscs.tmp")
    tmp.write_text(new)
    tmp.chmod(mode)
    os.replace(tmp, path)


def _alive(pid: int) -> bool:
    try:
        os.kill(pid, 0)
    except ProcessLookupError:
        return False
    except PermissionError:
        return True
    return True


def _live_sessions() -> list[Path]:
    live = []
    for f in SESSIONS_DIR.glob("*"):
        if f.name.isdigit() and _alive(int(f.name)):
            live.append(f)
        else:
            f.unlink(missing_ok=True)  # left behind by a killed session
    return live


@contextmanager
def vscode_include():
    """Let VS Code desktop see our hosts while this session runs.

    Several sessions can run at once: the block is removed by the last one
    to exit. A block left behind by a killed session is removed the next
    time, or by `foldspace-cscs <cluster> login`.
    """
    SESSIONS_DIR.mkdir(parents=True, exist_ok=True, mode=0o700)
    me = SESSIONS_DIR / str(os.getpid())
    me.touch()
    _rewrite_user_config(add=True)
    try:
        yield
    finally:
        me.unlink(missing_ok=True)
        if not _live_sessions():
            _rewrite_user_config(add=False)


def cleanup_stale_include() -> None:
    """Remove the Include block if no vscode session is running."""
    if not SESSIONS_DIR.exists() or not _live_sessions():
        _rewrite_user_config(add=False)
